"""The only sanctioned producer of performance numbers.

Rule 2 of CLAUDE.md: no accuracy, detection, latency or cost figure may appear
anywhere in this repository unless it was produced here, on a named dataset,
and written to ``eval/reports/``. This module is what makes a number sayable.

Run it:

    uv run python -m eval.run_eval synthetic-utopia-v1

It generates the protocol's documents, screens each one, and writes a report
that leads with what the numbers are **not**.
"""

from __future__ import annotations

import datetime
import hashlib
import shutil
import subprocess
import sys
from pathlib import Path
from typing import Final

from core.contracts import Artefact, Provenance, Subject
from datagen.forgeries.base import Forgery
from datagen.forgeries.copy_move import CopyMove
from datagen.forgeries.photo_substitution import PhotoSubstitution
from datagen.forgeries.recapture import Recapture
from datagen.forgeries.template_clone import TemplateClone
from datagen.forgeries.text_field_edit import TextFieldEdit
from datagen.synthetic_docs import generate_specimen
from detectors.base import Detector
from detectors.rung2_inference import metadata_forensics, tamper_classical, tamper_trufor
from eval.metrics import Outcome, Rates, separation, summarise
from eval.protocol import Protocol, load_protocol

REPORTS: Final[Path] = Path(__file__).parent / "reports"

GENERATORS: Final[dict[str, Forgery]] = {
    "photo_substitution": PhotoSubstitution(),
    "text_field_edit": TextFieldEdit(),
    "copy_move": CopyMove(),
    "recapture": Recapture(),
    "template_clone": TemplateClone(),
}

CAPTURED_AT: Final[datetime.datetime] = datetime.datetime(2026, 1, 1, 12, 0, tzinfo=datetime.UTC)

GIT: Final[str] = shutil.which("git") or "git"
"""Resolved rather than assumed, so the report records the commit or says unknown."""

SEPARATION_FLOOR: Final[float] = 0.1
"""A median gap smaller than this is not a signal, whatever its sign."""


def detectors() -> list[Detector]:
    """Return the Rung 2 detectors under evaluation.

    Rung 0 and Rung 1 detectors are absent on purpose: they are deterministic
    and are covered by golden tests, which assert an exact output rather than a
    rate. Measuring them here would produce a number where a proof already
    exists.
    """
    return [tamper_classical.build(), tamper_trufor.build(), metadata_forensics.build()]


def subject_for(png: bytes, label: str) -> Subject:
    """Build a subject from generated bytes, without running extraction.

    Extraction is deliberately skipped: these detectors read the artefact
    directly, and putting OCR in the loop would measure the reader as well as
    the detector.
    """
    return Subject(
        provenance=Provenance(
            source_id=label,
            sha256=hashlib.sha256(png).hexdigest(),
            media_type="image/png",
            byte_size=len(png),
            captured_at=CAPTURED_AT,
            received_at=CAPTURED_AT,
            checkpoint_id="eval",
        ),
        artefacts=(
            Artefact(
                role="document_front",
                media_type="image/png",
                sha256=hashlib.sha256(png).hexdigest(),
                data=png,
            ),
        ),
    )


def collect(protocol: Protocol) -> list[Outcome]:
    """Generate the dataset and screen every document in it."""
    outcomes: list[Outcome] = []
    built = detectors()

    for index in range(protocol.genuine_count):
        seed = protocol.seed + index
        specimen = generate_specimen(seed=seed)
        documents: list[tuple[str, bytes]] = [("genuine", specimen.png)]
        documents.extend(
            (name, GENERATORS[name].apply(specimen, seed=seed)) for name in protocol.forgeries
        )

        for document_class, png in documents:
            subject = subject_for(png, f"{document_class}-{seed}")
            for detector in built:
                if not detector.applies_to(subject):
                    continue
                for evidence in detector.run(subject):
                    outcomes.append(
                        Outcome(
                            detector_id=evidence.detector_id,
                            document_class=document_class,
                            result=evidence.result,
                            score=evidence.score,
                        )
                    )
    return outcomes


def commit() -> str:
    """Return the current commit, so a report names the code that produced it."""
    try:
        result = subprocess.run(  # noqa: S603 - fixed argument list, resolved binary, no shell
            [GIT, "rev-parse", "--short", "HEAD"],
            capture_output=True,
            text=True,
            check=True,
            cwd=Path(__file__).parent.parent,
        )
    except Exception:
        return "unknown"
    return result.stdout.strip() or "unknown"


def render(protocol: Protocol, rates: list[Rates]) -> str:
    """Render the report, leading with what the numbers do not mean."""
    today = datetime.date.today().isoformat()
    lines = [
        f"# Evaluation report — {protocol.name}",
        "",
        f"- **Dataset:** `{protocol.name}`, seed `{protocol.seed}`",
        f"- **Commit:** `{commit()}`",
        f"- **Run:** {today}",
        "",
        "## Read this before quoting any number below",
        "",
        "These figures measure **synthetic documents this repository generated**,",
        "rendered for a fictional issuing state in a font that is not OCR-B. They",
        "describe how the detectors behave on our own output.",
        "",
        "They are **not** a claim about real documents, they are **not** an accuracy",
        "figure for this system, and they must not be quoted as one. No real",
        "document has ever been screened by this project.",
        "",
        "There is no single headline number here on purpose. Averaging detection",
        "across forgery types hides which attacks a detector is blind to.",
        "",
        f"{protocol.description}",
        "",
        "## Results",
        "",
        "`escalated` is how often the detector said a person should look. On",
        "`genuine` rows that is the false-escalation rate — the number that decides",
        "whether an officer can work. `abstained` is how often it could not judge at",
        "all, reported separately and never folded into an error rate.",
        "",
        "| Detector | Documents | n | escalated | abstained | score q1 / median / q3 |",
        "|---|---|---|---|---|---|",
    ]
    for rate in rates:
        quartiles = rate.quartiles
        spread = (
            f"{quartiles[0]:.2f} / {quartiles[1]:.2f} / {quartiles[2]:.2f}" if quartiles else "—"
        )
        lines.append(
            f"| `{rate.detector_id}` | {rate.document_class} | {rate.count} | "
            f"{rate.escalation_rate:.0%} | {rate.abstention_rate:.0%} | {spread} |"
        )

    lines += ["", "## Does any signal actually separate?", ""]
    for detector_id in sorted({rate.detector_id for rate in rates}):
        gaps = separation(rates, detector_id)
        if not gaps:
            lines.append(
                f"- `{detector_id}`: produced no scores at all, so there is nothing to "
                f"separate. See its abstention rate above."
            )
            continue
        caught = {name: gap for name, gap in gaps.items() if gap > SEPARATION_FLOOR}
        blind = sorted(name for name, gap in gaps.items() if gap <= SEPARATION_FLOOR)
        if caught:
            detail = ", ".join(f"`{name}` {gap:+.2f}" for name, gap in sorted(caught.items()))
            lines.append(f"- `{detector_id}`: separates {detail} (median score above genuine).")
        if blind:
            listed = ", ".join(f"`{name}`" for name in blind)
            lines.append(
                f"- `{detector_id}`: **blind to** {listed} — no threshold makes these "
                f"detectable on this dataset."
            )
    lines.append("")
    return "\n".join(lines)


def main(argv: list[str] | None = None) -> int:
    """Run an evaluation protocol and write a report.

    Args:
        argv: Command line arguments; the protocol name.

    Returns:
        Process exit status.
    """
    arguments = sys.argv[1:] if argv is None else argv
    if not arguments:
        sys.stderr.write("usage: python -m eval.run_eval <protocol>\n")
        return 2

    protocol = load_protocol(arguments[0])
    rates = summarise(collect(protocol))

    REPORTS.mkdir(parents=True, exist_ok=True)
    destination = REPORTS / f"{protocol.name}-{datetime.date.today().isoformat()}.md"
    destination.write_text(render(protocol, rates), encoding="utf-8", newline="\n")
    sys.stdout.write(f"wrote {destination}\n")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
